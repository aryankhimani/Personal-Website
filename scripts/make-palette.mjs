// Builds the colour scales in OKLCH and writes src/styles/palette.css + src/data/palette.json.
// Each scale keeps its hue steady and eases chroma down at both ends, so tints stay clean and
// shades stay rich. Aryan's original hexes are pinned at the steps they belong to.
// Usage: node scripts/make-palette.mjs
import { writeFileSync } from 'node:fs';
import { hexToOklch, oklchToHex } from './oklch.mjs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const SCALES = {
  // Deep navy: the desk. 60% of every screen.
  navy: {
    hue: 268,
    L: [0.972, 0.935, 0.872, 0.767, 0.66, 0.56, 0.47, 0.41, 0.365, 0.266, 0.201],
    C: [0.008, 0.014, 0.024, 0.037, 0.05, 0.062, 0.074, 0.082, 0.085, 0.076, 0.057],
    pin: { 300: '#A9B3CC', 800: '#2C3B6B', 900: '#16224A', 950: '#0B1430' },
  },
  // Navy-tinted greys for secondary text and quiet UI. Never a pure grey.
  slate: {
    hue: 268,
    L: [0.97, 0.93, 0.86, 0.78, 0.69, 0.6, 0.51, 0.43, 0.35, 0.27, 0.21],
    C: [0.004, 0.007, 0.012, 0.018, 0.022, 0.025, 0.026, 0.026, 0.024, 0.02, 0.016],
    pin: {},
  },
  // Red-orange: the 10%. CTAs, focus, the ticker, Contact.
  ember: {
    hue: 32.3,
    L: [0.97, 0.935, 0.875, 0.8, 0.73, 0.667, 0.6, 0.541, 0.46, 0.38, 0.29],
    C: [0.016, 0.034, 0.068, 0.11, 0.16, 0.222, 0.2, 0.182, 0.152, 0.12, 0.09],
    pin: { 500: '#FF4A2B', 700: '#C2351B' },
  },
  // Warm cream: windows, reading surfaces, Journey. 30%.
  cream: {
    hue: 84.6,
    L: [0.975, 0.942, 0.905, 0.86, 0.79, 0.7, 0.6, 0.5, 0.4, 0.31, 0.24],
    C: [0.01, 0.02, 0.026, 0.03, 0.032, 0.032, 0.03, 0.026, 0.022, 0.018, 0.014],
    pin: { 100: '#F2EBDD' },
  },
};

const out = {};
for (const [name, s] of Object.entries(SCALES)) {
  out[name] = {};
  STEPS.forEach((step, i) => {
    out[name][step] = s.pin[step] ?? oklchToHex([s.L[i], s.C[i], s.hue]);
  });
}

// Extra hues for swarm cursor name tags only: desaturated so they sit inside the system.
const TAGS = { teal: [0.72, 0.09, 190], amber: [0.8, 0.12, 80], violet: [0.68, 0.11, 295], sky: [0.74, 0.09, 240] };
const tags = Object.fromEntries(Object.entries(TAGS).map(([k, v]) => [k, oklchToHex(v)]));
// Navy -> deep purple-navy, the only cross-hue gradient allowed.
const deep = oklchToHex([0.24, 0.08, 285]);

let css = '/* Generated by scripts/make-palette.mjs. Do not edit by hand. */\n@theme {\n';
for (const [name, scale] of Object.entries(out)) {
  for (const [step, hex] of Object.entries(scale)) css += `  --color-${name}-${step}: ${hex};\n`;
}
for (const [k, v] of Object.entries(tags)) css += `  --color-tag-${k}: ${v};\n`;
css += `  --color-indigo-deep: ${deep};\n}\n`;
writeFileSync('src/styles/palette.css', css);
writeFileSync('src/data/palette.json', JSON.stringify({ scales: out, tags, deep, oklch: Object.fromEntries(Object.entries(out).map(([n, sc]) => [n, Object.fromEntries(Object.entries(sc).map(([k, h]) => [k, hexToOklch(h).map((v) => +v.toFixed(3))]))])) }, null, 2));
console.log(JSON.stringify(out, null, 1), tags, deep);
